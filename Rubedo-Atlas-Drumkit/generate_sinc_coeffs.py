#!/usr/bin/env python3
"""Regenerate the CP08 24-tap, 64-phase resampler table.

Requires numpy. Output matches the reviewed CP08 coefficients byte-for-byte.
"""
from pathlib import Path
import numpy as np

out = Path(__file__).resolve().parent / "source" / "rubedo_sinc_coeffs.inc"
cutoffs = [0.94, 0.89, 0.84, 0.79, 0.74, 0.69, 0.64, 0.59, 0.54, 0.49, 0.44,
           0.39, 0.34, 0.29, 0.24, 0.19, 0.14, 0.10, 0.075, 0.055]
phases, taps = 64, 24
with out.open("w", encoding="utf-8") as f:
    f.write("/* CP08: immutable 24-tap, 64-phase Blackman-windowed, normalized SRC kernels.\n"
            "   Source and playback sample rates unchanged; kernel cutoff chosen conservatively for anti-aliasing.\n"
            "   Generated by make_hifi_engine.py, no runtime trigonometry or heap allocations. */\n")
    f.write("static const float rubedo_cutoffs[%d] = {%s};\n" %
            (len(cutoffs), ",".join(f"{c:.8g}f" for c in cutoffs)))
    f.write("static const float rubedo_polyphase[%d][%d][%d] = {\n" %
            (len(cutoffs), phases + 1, taps))
    for fc in cutoffs:
        f.write("{\n")
        for ph in range(phases + 1):
            frac = ph / phases
            x = np.arange(taps, dtype=np.float64) - 11 - frac
            w = 0.42 + 0.5 * np.cos(np.pi * x / (taps / 2)) + 0.08 * np.cos(2 * np.pi * x / (taps / 2))
            w[np.abs(x) >= taps / 2] = 0
            coeff = fc * np.sinc(fc * x) * w
            coeff /= np.sum(coeff)
            f.write("{" + ",".join(f"{c:.9g}f" if c != 0 else "0.0f" for c in coeff) + "},\n")
        f.write("},\n")
    f.write("};\n")
print(out)
